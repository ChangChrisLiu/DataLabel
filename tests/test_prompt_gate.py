def test_the_gate_is_on_for_scan_only_with_l1s_factor(shipped):
    assert shipped.views == frozenset({"scan"})
    assert shipped.k == 3.0
    for view in ("oak1", "oak2", "rs"):
        assert not shipped.applies(view)
        assert shipped.bands[view], f"no bands for {view}: it could not be turned on"


def test_the_bands_file_is_generated_in_pixels_from_parts_and_says_so():
    text = (PG.DEFAULT_FILE.parent / "prompt_box_bands.yaml").read_text("utf-8")
    assert "GENERATED by experiments/l1_localise/fit_bands.py" in text
    doc = yaml.safe_load(text)
    assert doc["unit"] == "image px"
    assert doc["min_parts"] == 5 and doc["min_desktops"] == 2       # U2i
    for view, entry in doc["views"].items():
        for cls, row in entry["classes"].items():
            assert row["parts"] >= 5 and row["desktops"] >= 2, (view, cls)
            assert row["keyframes"] >= row["parts"], (view, cls)
            assert 0 < row["lo_px"] <= row["median_px"] <= row["hi_px"], (view, cls)
        for cls, counts in (entry.get("unbanded") or {}).items():
            assert counts["parts"] < 5 or counts["desktops"] < 2, (view, cls)
            assert cls not in entry["classes"]


def test_one_long_lived_part_is_not_a_class():
    """U2i: one GPU on one desktop, drawn on 32 steps, used to get 1,359-1,359 px."""
    doc = yaml.safe_load((PG.DEFAULT_FILE.parent / "prompt_box_bands.yaml")
                         .read_text("utf-8"))
    scan = doc["views"]["scan"]
    assert "expansion_card" not in scan["classes"]
    assert scan["unbanded"]["expansion_card"] == {"parts": 1, "desktops": 1}
    assert "cooler_bracket" not in scan["classes"]                 # 3 real brackets
    assert scan["unbanded"]["cooler_bracket"]["parts"] == 3


def test_d13_scan_37s_cable_box_is_withheld_and_38s_blob_is_kept(shipped):
    lo, hi = shipped.band("scan", "screw")
    assert D13_37_CABLE_PX > 3 * hi
    verdict = shipped.judge("scan", ["screw"], D13_37_CABLE_PX)
    assert verdict is not None and verdict.classes == ("screw",)
    assert verdict.factor == pytest.approx(D13_37_CABLE_PX / hi)
    assert shipped.judge("scan", ["screw"], D13_38_BLOB_PX) is None
    # the same box on a view the gate is off for is armed as before
    assert shipped.judge("oak2", ["screw"], D13_37_CABLE_PX) is None


def test_a_class_without_a_band_is_never_gated(shipped):
    assert shipped.band("scan", "cooler_bracket") is None      # 3 parts
    assert shipped.judge("scan", ["cooler_bracket"], 10 ** 9) is None
    assert shipped.judge("scan", ["screw", "cooler_bracket"], 10 ** 9) is None


# --------------------------------------------------------------------------- #
# the rule
# --------------------------------------------------------------------------- #
def gate() -> PG.PromptGate:
    return PG.PromptGate(["scan"], 3.0, {"scan": {"screw": (100.0, 400.0),
                                                 "psu": (80_000.0, 120_000.0)}})


@pytest.mark.parametrize("area, withheld", [
    (33, True), (33.4, False), (100, False), (400, False),
    (1200, False), (1201, True), (6332, True)])
def test_k_is_a_factor_outside_the_band_either_way(area, withheld):
    assert (gate().judge("scan", ["screw"], area) is not None) is withheld


def test_several_classes_keep_the_box_if_any_band_fits():
    g = gate()
    assert g.judge("scan", ["screw", "psu"], 100_000) is None      # the PSU's
    assert g.judge("scan", ["screw", "psu"], 300) is None          # the screw's
    verdict = g.judge("scan", ["screw", "psu"], 6332)
    assert verdict is not None and verdict.classes == ("screw", "psu")
    # the factor is the nearest band's: 80,000 / 6,332 (12.6) beats 6,332 / 400 (15.8)
    assert verdict.factor == pytest.approx(80_000 / 6332)


def test_nothing_asked_for_or_another_view_keeps_the_box():
    g = gate()
    assert g.judge("scan", [], 6332) is None
    assert g.judge("scan", ["", None], 6332) is None
    assert g.judge("oak1", ["screw"], 6332) is None


def test_outside_factor_is_l1s():
    assert PG.outside_factor(50, (100, 400)) == 2.0
    assert PG.outside_factor(800, (100, 400)) == 2.0
    assert PG.outside_factor(200, (100, 400)) == 1.0
    assert PG.outside_factor(200, None) == 1.0
    assert PG.outside_factor(0, (100, 400)) == 1.0


