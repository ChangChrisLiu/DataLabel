def _draft(desktop, key, area, cls="screw", view="scan", step=1):
    return {"desktop": desktop, "view": view, "step": step, "instance": key,
            "cls": cls, "area": area, "box": (0, 0, 1, 1)}


def test_a_part_drawn_on_many_steps_counts_once_at_its_median():
    from experiments.l1_localise import fit_bands as F

    drafts = [_draft(13, "ls:GPU#1", 1359, "expansion_card", step=s) for s in range(32)]
    parts = F.part_values(drafts, "scan", "expansion_card")
    assert parts == [(1359.0, 13, 32)]
    assert F.band_of(parts) is None
    # one part, many keyframes of varying size: its median, once
    wobbly = [_draft(13, "ls:Screw#1", a) for a in (100, 300, 200, 250, 5000)]
    assert F.part_values(wobbly, "scan", "screw") == [(250.0, 13, 5)]


def test_a_band_needs_five_parts_from_two_desktops():
    from experiments.l1_localise import fit_bands as F

    one_desktop = [_draft(13, f"ls:Screw#{i}", 200 + i) for i in range(9)]
    assert F.band_of(F.part_values(one_desktop, "scan", "screw")) is None
    four = [_draft(13, "ls:Screw#1", 200), _draft(13, "ls:Screw#2", 210),
            _draft(24, "ls:Screw#1", 220), _draft(24, "ls:Screw#2", 230)]
    assert F.band_of(F.part_values(four, "scan", "screw")) is None
    five = four + [_draft(33, "ls:Screw#1", 240)]
    band = F.band_of(F.part_values(five, "scan", "screw"))
    assert band["parts"] == 5 and band["desktops"] == 3 and band["keyframes"] == 5
    assert band["lo_px"] == pytest.approx(202.0) and band["hi_px"] == pytest.approx(238.0)
    # leave-one-desktop-out: without D33 it is four parts again
    assert F.band_of(F.part_values(five, "scan", "screw", exclude_desktop=33)) is None
    fitted = F.fit(five + one_desktop[:1], views=("scan",))["scan"]
    assert set(fitted["classes"]) == {"screw"} and fitted["unbanded"] == {}
