"""The "no box when unsure" gate (task U2h, :mod:`tda.ui.prompt_gate`).

L1's M1 (``experiments/l1_localise/REPORT.md``): withhold the difference map's
rank-1 box when its blob's area is outside the area band of every class the
frame asks to add back by more than ``k``.  The window half is in
``tests/test_app_u2h.py``.
"""
from __future__ import annotations

import pytest
import yaml

from tda.ui import prompt_gate as PG

#: D13/scan, the annotator's report that started L1: on frame 37 the rank-1
#: blob was 6,332 px on a black cable, the part a screw (screw.motherboard.03);
#: on frame 38 it was 121 px on a capacitor next to the screw.
D13_37_CABLE_PX = 6332
D13_38_BLOB_PX = 121


@pytest.fixture(scope="module")
def shipped() -> PG.PromptGate:
    return PG.load_prompt_gate(str(PG.DEFAULT_FILE))


